"""Generate AfterCraft's original purple AC/layers mark (MIT OR Apache-2.0).

Requires Pillow. All geometry below is original; no third-party artwork is loaded.
The SVG, PNG and ICO share the same shapes. Render at 4x before downsampling.
"""

import pathlib

from PIL import Image, ImageDraw

ROOT = pathlib.Path(__file__).resolve().parents[2]
ASSETS = ROOT / "assets/aftercraft"
BACKGROUND = "#211334"
SHAPES = [
    ("#4b276c", [(90, 351), (256, 434), (422, 351), (422, 376), (256, 459), (90, 376)]),
    ("#7d49a6", [(90, 319), (256, 402), (422, 319), (422, 344), (256, 427), (90, 344)]),
    ("#c7a0ff", [(86, 318), (153, 126), (204, 126), (271, 318), (223, 318), (212, 282), (145, 282), (134, 318)]),
    (BACKGROUND, [(158, 241), (199, 241), (179, 171)]),
    ("#f1e8ff", [(415, 164), (383, 132), (312, 132), (270, 174), (270, 270), (312, 312), (383, 312), (415, 280),
                 (384, 249), (366, 267), (332, 267), (315, 250), (315, 194), (332, 177), (366, 177), (384, 195)]),
]


def generate():
    ASSETS.mkdir(parents=True, exist_ok=True)
    svg = [
        '<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">',
        f'<rect x="32" y="32" width="448" height="448" rx="96" fill="{BACKGROUND}"/>',
    ]
    image = Image.new("RGBA", (2048, 2048))
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((128, 128, 1919, 1919), radius=384, fill=BACKGROUND)
    for color, points in SHAPES:
        svg.append('<polygon fill="' + color + '" points="' + ' '.join(f'{x},{y}' for x, y in points) + '"/>')
        draw.polygon([(x * 4, y * 4) for x, y in points], fill=color)
    svg.append('</svg>')
    (ASSETS / "aftercraft.svg").write_text('\n'.join(svg) + '\n', encoding="utf-8")
    icon = image.resize((256, 256), Image.Resampling.LANCZOS)
    icon.save(ASSETS / "aftercraft-256.png")
    icon.save(ASSETS / "aftercraft.ico", sizes=[(16, 16), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    index = ROOT / "ATTRIBUTION.md"
    text = index.read_text(encoding="utf-8")
    for name in ["aftercraft.svg", "aftercraft-256.png", "aftercraft.ico"]:
        (ASSETS / (name + ".attribution")).write_text(f'''asset: {name}
title: AfterCraft AC and offset layers mark
author: AfterCraft contributors
source: original work; tools/brand/generate.py
license: MIT OR Apache-2.0
license-file: ../../LICENSE-MIT
added: 2026-10-25 by AfterCraft contributors
notes: Replaced on 2026-10-27 with the user-selected original AC/layers design in purple. Original polygon geometry; no Adobe or ArtCraft artwork copied or traced.
''', encoding="utf-8")
        relative = 'assets/aftercraft/' + name
        if '`' + relative + '`' not in text:
            text += f'\n- `{relative}` — Original AfterCraft contributors; MIT OR Apache-2.0; generated by tools/brand/generate.py.\n'
    index.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    generate()
